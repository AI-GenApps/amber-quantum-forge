import { existsSync, readdirSync, readFileSync } from "node:fs";
import { join } from "node:path";
import sharp from "sharp";
import { describe, expect, it } from "vitest";
import { loadSlotTable } from "../../scripts/art-lib";
import { ART_MANIFEST } from "../../src/ui/art-manifest";
import { ART_SLOTS, type ArtSlot, slotSpec } from "../../src/ui/art-slots";
import { APP, ART_DIR, acceptedEntries, isWebp, PUBLIC } from "./paths";

const table = loadSlotTable(join(APP, "scripts", "art-slots.json"));
const entries = Object.entries(ART_MANIFEST) as [ArtSlot, (typeof ART_MANIFEST)[ArtSlot]][];

describe("slot table", () => {
  it("lists exactly the 33 slots, in the same names as the app", () => {
    expect(table.slots.map((slot) => slot.id).sort()).toEqual([...ART_SLOTS].sort());
    expect(table.slots).toHaveLength(33);
    expect(table.scale).toBe(2);
  });

  it("agrees with the app's display sizes, and bundles every slot but icon and feature-graphic", () => {
    for (const row of table.slots) {
      if (!row.bundled) {
        expect(["icon", "feature-graphic"]).toContain(row.id);
        expect(row.display).toBeNull();
        continue;
      }
      const spec = slotSpec(row.id as ArtSlot);
      expect(row.display, row.id).toEqual([spec.width, spec.height]);
    }
    expect(table.slots.filter((row) => row.bundled)).toHaveLength(31);
  });
});

describe("shipped art manifest", () => {
  it("only names slots that exist, and only bundled ones", () => {
    for (const [slot] of entries) {
      const row = table.slots.find((candidate) => candidate.id === slot);
      expect(row?.bundled, slot).toBe(true);
    }
  });

  it("is exactly the accepted bundled slots", () => {
    const accepted = acceptedEntries().map((entry) => entry.assetId);
    const bundled = table.slots.filter((row) => row.bundled && accepted.includes(row.id));
    expect(entries.map(([slot]) => slot).sort()).toEqual(bundled.map((row) => row.id).sort());
    const files = readdirSync(ART_DIR).sort();
    expect(files).toEqual(bundled.map((row) => `${row.id}.webp`).sort());
  });

  for (const [slot, entry] of entries) {
    describe(slot, () => {
      const file = join(PUBLIC, entry?.src ?? "missing");
      const row = table.slots.find((candidate) => candidate.id === slot);

      it("has a WebP file whose dimensions are 2x the display size", async () => {
        expect(entry?.src).toBe(`/art/${slot}.webp`);
        expect(existsSync(file)).toBe(true);
        expect(isWebp(file)).toBe(true);
        const meta = await sharp(file).metadata();
        expect(meta.format).toBe("webp");
        const spec = slotSpec(slot);
        expect([meta.width, meta.height]).toEqual([spec.width * 2, spec.height * 2]);
        expect([entry?.width, entry?.height]).toEqual([meta.width, meta.height]);
      });

      it("keeps an alpha channel with transparent corners on transparent slots", async () => {
        const meta = await sharp(file).metadata();
        if (!row?.transparent) {
          expect(entry?.background).toMatch(/^#[0-9A-F]{6}$/);
          return;
        }
        expect(meta.hasAlpha).toBe(true);
        expect(entry?.background).toBe("transparent");
        const { data, info } = await sharp(file)
          .ensureAlpha()
          .raw()
          .toBuffer({ resolveWithObject: true });
        const alphaAt = (x: number, y: number): number => data[(y * info.width + x) * 4 + 3] ?? 255;
        expect([
          alphaAt(0, 0),
          alphaAt(info.width - 1, 0),
          alphaAt(0, info.height - 1),
          alphaAt(info.width - 1, info.height - 1),
        ]).toEqual([0, 0, 0, 0]);
      });
    });
  }

  it("generated module matches the build report", () => {
    const source = readFileSync(join(APP, "src/ui/art-entries.ts"), "utf8");
    expect(source).toContain("Generated by scripts/build-art.mjs");
    for (const [slot, entry] of entries) {
      expect(source).toContain(`"${slot}": {`);
      expect(source).toContain(`src: "${entry?.src}"`);
    }
  });
});
