import { createHash } from "node:crypto";
import { readFileSync } from "node:fs";
import type { Sharp } from "sharp";

export interface SlotRow {
  id: string;
  batch: string;
  transparent: boolean;
  bundled: boolean;
  /** Display size in CSS px; null for slots that are masters only. */
  display: [number, number] | null;
  /** Generation size the designer delivers. */
  master: [number, number];
  /** Corners that must be fully transparent: all four (default) or only the top two (bottom-anchored layers). */
  transparentCorners?: "all" | "top";
}

export interface SlotTable {
  scale: number;
  masterQuality: number;
  bundledQuality: number;
  bundledAlphaQuality: number;
  slots: SlotRow[];
}

export interface InboxEntry {
  assetId: string;
  file: string;
  size: string;
  transparent: boolean;
  round: number;
  batch: string;
}

export interface SourceInfo {
  width: number;
  height: number;
  hasAlpha: boolean;
  /** Alpha of the four corner pixels (255 when the file has no alpha). */
  cornerAlpha: [number, number, number, number];
}

export const ASPECT_TOLERANCE = 0.01;

export function loadSlotTable(path: string): SlotTable {
  return JSON.parse(readFileSync(path, "utf8")) as SlotTable;
}

export function targetSize(slot: SlotRow, scale: number): [number, number] | null {
  return slot.display ? [slot.display[0] * scale, slot.display[1] * scale] : null;
}

/** Alpha of the corners the slot requires to be transparent (top two only for bottom-anchored layers). */
export function cornersToCheck(slot: SlotRow, cornerAlpha: SourceInfo["cornerAlpha"]): number[] {
  return slot.transparentCorners === "top" ? cornerAlpha.slice(0, 2) : [...cornerAlpha];
}

/** Every reason a source image cannot be used for its slot; empty means it passes. */
export function checkSource(slot: SlotRow, info: SourceInfo, scale: number): string[] {
  const problems: string[] = [];
  const [mw, mh] = slot.master;
  const sourceAspect = info.width / info.height;
  if (Math.abs(sourceAspect / (mw / mh) - 1) > ASPECT_TOLERANCE) {
    problems.push(
      `${slot.id}: aspect ${info.width}x${info.height} does not match the slot class ${mw}x${mh}`,
    );
  }
  if (slot.transparent) {
    if (!info.hasAlpha) problems.push(`${slot.id}: transparent slot but the source has no alpha`);
    else if (cornersToCheck(slot, info.cornerAlpha).some((alpha) => alpha !== 0)) {
      problems.push(`${slot.id}: transparent slot but a corner pixel is not fully transparent`);
    }
  }
  const target = targetSize(slot, scale);
  if (target && (info.width < target[0] || info.height < target[1])) {
    problems.push(
      `${slot.id}: source ${info.width}x${info.height} is smaller than the ${target[0]}x${target[1]} target`,
    );
  }
  return problems;
}

export async function readSourceInfo(image: Sharp): Promise<SourceInfo> {
  const meta = await image.metadata();
  const width = meta.width ?? 0;
  const height = meta.height ?? 0;
  const hasAlpha = meta.hasAlpha === true;
  if (!hasAlpha) {
    return { width, height, hasAlpha, cornerAlpha: [255, 255, 255, 255] };
  }
  const { data, info } = await image
    .clone()
    .ensureAlpha()
    .raw()
    .toBuffer({ resolveWithObject: true });
  const at = (x: number, y: number): number =>
    data[(y * info.width + x) * info.channels + 3] ?? 255;
  return {
    width,
    height,
    hasAlpha,
    cornerAlpha: [at(0, 0), at(width - 1, 0), at(0, height - 1), at(width - 1, height - 1)],
  };
}

export function sha256(bytes: Uint8Array): string {
  return createHash("sha256").update(bytes).digest("hex");
}

export function toHex(r: number, g: number, b: number): string {
  const part = (v: number): string =>
    Math.max(0, Math.min(255, Math.round(v)))
      .toString(16)
      .padStart(2, "0");
  return `#${part(r)}${part(g)}${part(b)}`.toUpperCase();
}

export interface ManifestEntry {
  id: string;
  src: string;
  width: number;
  height: number;
  background: string;
}

/** Source of `src/ui/art-entries.ts`; sorted by slot id so reruns are byte-identical. */
export function renderEntriesModule(entries: readonly ManifestEntry[]): string {
  const sorted = [...entries].sort((a, b) => a.id.localeCompare(b.id));
  const body = sorted
    .map(
      (e) =>
        `  "${e.id}": {\n    src: "${e.src}",\n    width: ${e.width},\n    height: ${e.height},\n    background: "${e.background}",\n  },`,
    )
    .join("\n");
  return [
    "// Generated by scripts/build-art.mjs from the accepted designer images. Do not edit by hand.",
    'import type { ArtManifest } from "./art-manifest";',
    "",
    sorted.length === 0
      ? "export const ART_ENTRIES: ArtManifest = {};"
      : `export const ART_ENTRIES: ArtManifest = {\n${body}\n};`,
    "",
  ].join("\n");
}
