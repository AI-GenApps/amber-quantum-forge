import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { encodePuzzle, encodeTiles } from "../src/code";
import { analyseRecord, median, type RecordStats } from "../src/content/analyse";
import { BRIDGE_PUZZLES } from "../src/content/campaign/bridge";
import { GARDEN_PUZZLES } from "../src/content/campaign/garden";
import { HARBOR_PUZZLES } from "../src/content/campaign/harbor";
import { SKY_PUZZLES } from "../src/content/campaign/sky";
import { campaignSpecs } from "../src/content/spec";
import { CHAPTER_IDS, type ChapterId, type PuzzleRecord } from "../src/content/types";
import { validateCampaign } from "../src/content/validate";
import { generatePuzzle } from "../src/gen/generate";

const ROOT = join(import.meta.dirname, "..");
const DATA_DIR = join(ROOT, "src", "content", "campaign");
const REPORT_DIR = join(
  ROOT,
  "..",
  "..",
  ".agents",
  "resources",
  "2026-10-23",
  "web-games",
  "lantern-loops",
  "02",
);
const REPORT_PATH = join(REPORT_DIR, "campaign-report.json");

const CURRENT: Readonly<Record<ChapterId, readonly PuzzleRecord[]>> = {
  harbor: HARBOR_PUZZLES,
  garden: GARDEN_PUZZLES,
  bridge: BRIDGE_PUZZLES,
  sky: SKY_PUZZLES,
};

function recordSource(record: PuzzleRecord): string {
  return [
    "  {",
    `    id: ${JSON.stringify(record.id)},`,
    `    chapter: ${JSON.stringify(record.chapter)},`,
    `    index: ${record.index},`,
    `    title: ${JSON.stringify(record.title)},`,
    `    size: ${record.size},`,
    `    code: ${JSON.stringify(record.code)},`,
    `    solution: ${JSON.stringify(record.solution)},`,
    `    rating: ${record.rating},`,
    `    seed: ${record.seed},`,
    "  },",
  ].join("\n");
}

function writeChapter(chapter: ChapterId, records: readonly PuzzleRecord[]): void {
  const name = `${chapter.toUpperCase()}_PUZZLES`;
  const text = [
    `import type { PuzzleRecord } from "../types";`,
    "",
    "// Generated by scripts/generate-campaign.ts (generator ll-gen-1). Do not edit by hand.",
    `export const ${name}: readonly PuzzleRecord[] = [`,
    ...records.map(recordSource),
    "];",
    "",
  ].join("\n");
  writeFileSync(join(DATA_DIR, `${chapter}.ts`), text);
}

function buildReport(records: readonly PuzzleRecord[]): RecordStats[] {
  return records.map((record) => analyseRecord(record));
}

function serialise(report: readonly RecordStats[]): string {
  return `${JSON.stringify(report, null, 2)}\n`;
}

function printSummary(report: readonly RecordStats[]): void {
  for (const chapter of CHAPTER_IDS) {
    const rows = report.filter((row) => row.id.startsWith(`${chapter}-`));
    if (rows.length === 0) continue;
    const shares = rows.map((row) => row.anchorShare);
    const maxNodes = Math.max(...rows.map((row) => row.nodes));
    const ratings = rows.map((row) => row.rating).join("");
    console.log(
      `${chapter.padEnd(7)} n=${rows.length} anchor share median ${median(shares)}% max ${Math.max(...shares)}% max nodes ${maxNodes} ratings ${ratings}`,
    );
  }
}

function verify(): number {
  const issues = validateCampaign();
  for (const issue of issues) console.error(`${issue.id}: ${issue.message}`);
  const all = CHAPTER_IDS.flatMap((chapter) => CURRENT[chapter]);
  let reportOk = false;
  try {
    reportOk = readFileSync(REPORT_PATH, "utf8") === serialise(buildReport(all));
  } catch {
    reportOk = false;
  }
  if (!reportOk) console.error(`report ${REPORT_PATH} is missing or out of date`);
  printSummary(buildReport(all));
  console.log(
    `verify: ${all.length} puzzles, ${issues.length} issues, report ${reportOk ? "ok" : "stale"}`,
  );
  return issues.length === 0 && reportOk ? 0 : 1;
}

function generate(only: string | null): number {
  const next: Record<ChapterId, PuzzleRecord[]> = {
    harbor: [...HARBOR_PUZZLES],
    garden: [...GARDEN_PUZZLES],
    bridge: [...BRIDGE_PUZZLES],
    sky: [...SKY_PUZZLES],
  };
  let failures = 0;
  const specs = campaignSpecs().filter((spec) => only === null || spec.id === only);
  if (specs.length === 0) {
    console.error(`no puzzle matches ${only}`);
    return 1;
  }
  for (const spec of specs) {
    const started = performance.now();
    const made = generatePuzzle(spec.params, spec.seed);
    const record: PuzzleRecord = {
      id: spec.id,
      chapter: spec.chapter,
      index: spec.index,
      title: spec.title,
      size: spec.size,
      code: encodePuzzle(made.puzzle),
      solution: encodeTiles(made.solution),
      rating: made.rating,
      seed: spec.seed,
    };
    const list = next[spec.chapter];
    const at = list.findIndex((existing) => existing.id === spec.id);
    if (at >= 0) list[at] = record;
    else list.push(record);
    if (!made.accepted) failures += 1;
    const ms = (performance.now() - started).toFixed(0);
    console.log(
      `${spec.id.padEnd(10)} ${made.accepted ? "ok " : "MISS"} rating ${made.rating} anchors ${made.anchors}/${made.solutionTiles} nodes ${made.stats.nodes} attempt ${made.attempt}${made.fallback ? " fallback" : ""} ${ms}ms`,
    );
  }
  for (const chapter of CHAPTER_IDS) {
    next[chapter].sort((a, b) => a.index - b.index);
    writeChapter(chapter, next[chapter]);
  }
  const all = CHAPTER_IDS.flatMap((chapter) => next[chapter]);
  mkdirSync(REPORT_DIR, { recursive: true });
  const report = buildReport(all);
  writeFileSync(REPORT_PATH, serialise(report));
  printSummary(report);
  if (failures > 0) console.error(`${failures} puzzles missed their limits`);
  return failures === 0 ? 0 : 1;
}

const args = process.argv.slice(2);
const onlyAt = args.indexOf("--only");
const only = onlyAt >= 0 ? (args[onlyAt + 1] ?? null) : null;
process.exit(args.includes("--verify") ? verify() : generate(only));
