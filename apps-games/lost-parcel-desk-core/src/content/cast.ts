import type { PersonContent } from "./types";

function person(
  n: number,
  name: string,
  trade: string,
  street: string,
  pastime: string,
  look: string,
  pet: string,
  bio: string,
): PersonContent {
  const pad = String(n).padStart(2, "0");
  return {
    id: `p${pad}`,
    name,
    trade,
    facets: { street, pastime, look, pet },
    bio,
    portraitSlot: `townsfolk-${n}`,
    ownsCaseId: pad,
  };
}

