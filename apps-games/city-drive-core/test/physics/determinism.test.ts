import { readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import { createScenarioRig, hashPerSecond, runScenario, SCENARIO_SECONDS } from "./scenario";

const FIXTURE = join(import.meta.dirname, "..", "fixtures", "determinism.json");

describe("determinism", () => {
  it("replays the 30 s script to identical hashes at every second", async () => {
    const a = await hashPerSecond();
    const b = await hashPerSecond();
    expect(a).toHaveLength(SCENARIO_SECONDS);
    expect(b).toEqual(a);
    expect(new Set(a).size).toBeGreaterThan(SCENARIO_SECONDS - 3); // the car really moves
  });

  it("matches the hash fixture generated by tool/gen-determinism-fixture.ts", async () => {
    const fixture = JSON.parse(readFileSync(FIXTURE, "utf8")) as { hashes: string[] };
    expect(await hashPerSecond()).toEqual(fixture.hashes);
  });

  it("snapshot -> restore -> continue equals an uninterrupted run", async () => {
    const SNAP = 600;
    const END = 1200;
    const reference = await createScenarioRig();
    const refHashes = new Map<number, string>();
    runScenario(reference, 0, END, (tick) => {
      if (tick % 60 === 0) refHashes.set(tick, reference.car.hash());
    });

    const rig = await createScenarioRig();
    runScenario(rig, 0, SNAP);
    const snapshot = rig.world.takeSnapshot();
    runScenario(rig, SNAP, SNAP + 300); // diverge, then rewind
    rig.world.restoreSnapshot(snapshot);
    expect(rig.world.tick).toBe(SNAP);
    const restored = new Map<number, string>();
    runScenario(rig, SNAP, END, (tick) => {
      if (tick % 60 === 0) restored.set(tick, rig.car.hash());
    });
    for (const [tick, hash] of restored) expect(hash, `tick ${tick}`).toBe(refHashes.get(tick));
  });
});
