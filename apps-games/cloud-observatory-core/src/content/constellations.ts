import type { ConstellationDef, InstrumentId, Point } from "../types";

type Row = readonly [number, number];

function stars(rows: readonly Row[]): readonly Point[] {
  return rows.map(([x, y]) => ({ x, y }));
}

function def(
  id: string,
  name: string,
  rows: readonly Row[],
  closed: boolean,
  cost: number,
  instrumentId: InstrumentId,
  count: number,
): ConstellationDef {
  return { id, name, stars: stars(rows), closed, cost, requires: { instrumentId, count } };
}

