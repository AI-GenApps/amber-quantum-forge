import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { generateAttempt } from "../src/daily/generate";
import { DAILY_TIERS } from "../src/daily/tiers";
import { hashString } from "../src/prng";
import type { Placement } from "../src/types";

const PER_TIER = 2;
const OUT = join(import.meta.dirname, "..", "src", "daily", "fallbacks.ts");

function piece(p: Placement): string {
  switch (p.kind) {
    case "canal":
      return `c(${p.x}, ${p.y})`;
    case "barrier":
      return `b(${p.x}, ${p.y})`;
    case "pump":
      return `p(${p.x}, ${p.y}, "${p.dir}")`;
    case "gate":
      return `g(${p.x}, ${p.y}, ${p.opensWeek}, ${p.closesWeek})`;
    default:
      return `r(${p.x}, ${p.y})`;
  }
}

function entries(): string[] {
  const out: string[] = [];
  for (const tier of DAILY_TIERS) {
    for (let k = 0; k < PER_TIER; k++) {
      let made = null;
      for (let n = 0; made === null && n < 200; n++) {
        const seed = hashString(`fallback|${tier.weekday}|${k}|${n}`);
        made = generateAttempt(seed, tier, 0).map;
      }
      if (!made) throw new Error(`no fallback for weekday ${tier.weekday}`);
      out.push(`  {
    weekday: ${tier.weekday},
    map: {
      layout: ${JSON.stringify(made.layout)},
      inlets: ${JSON.stringify(made.inlets)},
      houseKinds: ${JSON.stringify(made.houseKinds)},
      events: ${JSON.stringify(made.events)},
      tide: ${JSON.stringify(made.tide)},
      weeks: ${made.weeks},
      pieces: ${JSON.stringify(made.pieces)},
      par: ${made.par},
      budget: ${made.budget},
      reference: [${made.reference.map(piece).join(", ")}],
    },
  }`);
    }
  }
  return out;
}

const header = (helpers: string): string => `import { ${helpers} } from "../content/dsl";
import type { DailyMap } from "./generate";

export interface FallbackTemplate {
  weekday: number;
  map: DailyMap;
}

// Generated by scripts/gen-fallbacks.ts: 2 proven templates per weekday tier.
export const FALLBACK_TEMPLATES: readonly FallbackTemplate[] = [
`;

const body = entries().join(",\n");
const used = ["b", "c", "g", "p", "r"].filter((name) => body.includes(`${name}(`));
writeFileSync(OUT, `${header(used.join(", "))}${body},\n];\n`);
console.log("wrote", OUT);
